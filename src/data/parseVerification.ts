export interface ParsedMember {
  id: string;
  nome: string;
  instrumento: string;
  localidade: string;
  cargo: string;
  nivel: string;
  pagina: number;
}

export function parseOcrText(text: string): { members: ParsedMember[]; errors: any[] } {
  const lines = text.split('\n');
  let currentPage = 1;
  const members: ParsedMember[] = [];
  const errors: any[] = [];

  for (let rawLine of lines) {
    let line = rawLine.trim();
    if (!line) continue;
    if (line.includes('==Start of OCR for page')) {
      const match = line.match(/page (\d+)/);
      if (match) currentPage = parseInt(match[1]);
      continue;
    }
    if (line.startsWith('Sistema de') || line.startsWith('RELATÓRIO') || line.startsWith('Gerado em:') || line.startsWith('NOME INSTRUMENTO') || line.startsWith('Página ') || line.startsWith('Total:') || line.startsWith('==End of OCR')) {
      continue;
    }

    // Attempt to match from the right:
    // 1. NIVEL
    let foundNivel = '';
    for (const lvl of levels) {
      if (line.endsWith(lvl)) {
        foundNivel = lvl;
        line = line.slice(0, line.length - lvl.length).trim();
        break;
      }
    }

    if (!foundNivel) {
      errors.push({ line: rawLine, page: currentPage, reason: 'Nível não identificado' });
      continue;
    }

    // 2. CARGO/MINISTÉRIO
    let foundCargo = '';
    for (const crg of cargos) {
      if (line.endsWith(crg)) {
        foundCargo = crg;
        line = line.slice(0, line.length - crg.length).trim();
        break;
      }
    }

    if (!foundCargo) {
      errors.push({ line: rawLine, page: currentPage, reason: 'Cargo não identificado' });
      continue;
    }

    // In remaining line: NOME INSTRUMENTO LOCALIDADE
    // Let's find INSTRUMENTO inside the line
    let foundInst = '';
    let instIndex = -1;
    for (const inst of instruments) {
      // Find instrument surrounded by spaces or matching boundaries
      const regex = new RegExp(`\\s+${inst.replace(/\(/g, '\\(').replace(/\)/g, '\\)')}\\s+`);
      const match = regex.exec(line);
      if (match) {
        foundInst = inst;
        instIndex = match.index;
        const nome = line.slice(0, instIndex).trim();
        const localidade = line.slice(instIndex + match[0].length).trim();
        members.push({
          id: 'mem_' + (members.length + 1),
          nome,
          instrumento: foundInst,
          localidade,
          cargo: foundCargo,
          nivel: foundNivel,
          pagina: currentPage
        });
        break;
      }
    }

    if (!foundInst) {
      // Handle special cases if any
      errors.push({ line: rawLine, page: currentPage, reason: 'Instrumento não identificado' });
    }
  }

  return { members, errors };
}

